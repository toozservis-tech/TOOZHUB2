"""Public deletion instructions must be usable without an account or app.

Only GET requests against a local ASGI app; never deletes an account or sends mail.
"""
from html.parser import HTMLParser
from pathlib import Path
from unittest.mock import patch
from urllib.parse import urljoin, urlsplit

from fastapi import FastAPI
from fastapi.testclient import TestClient

from src.server.web_access import AdminStaticFiles, PUBLIC_WEB_PAGES, router


ROOT = Path(__file__).resolve().parents[2]


class Links(HTMLParser):
    def __init__(self, html):
        super().__init__()
        self.hrefs = []
        self.tags = []
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        self.tags.append(tag)
        if tag == "a":
            self.hrefs.append(dict(attrs).get("href", ""))


def public_client():
    app = FastAPI()
    app.include_router(router)
    app.mount("/web", AdminStaticFiles(directory=ROOT / "web", html=True, public_pages=PUBLIC_WEB_PAGES))
    return TestClient(app)


def test_deletion_page_is_public_without_cookie_or_database():
    with patch("src.server.web_access.SessionLocal", side_effect=AssertionError("Public instructions must not require a database or login")):
        response = public_client().get("/web/smazani-uctu.html", follow_redirects=False)
    assert response.status_code == 200
    assert response.headers["content-type"].startswith("text/html")
    assert response.headers["cache-control"] == "no-store"
    assert "Evidence Vozidel" in response.text
    assert 'lang="cs"' in response.text


def test_public_deletion_links_reach_real_pages_without_authentication():
    client = public_client()
    with patch("src.server.web_access.SessionLocal", side_effect=AssertionError("Public path unexpectedly required login")):
        html = client.get("/web/smazani-uctu.html").text
        parsed = Links(html)
        paths = {urlsplit(urljoin("/web/smazani-uctu.html", href)).path for href in parsed.hrefs if not urlsplit(href).scheme}
        assert paths == {"/web/customer.html", "/web/ochrana-osobnich-udaju.html"}
        for path in paths:
            response = client.get(path, follow_redirects=False)
            assert response.status_code == 200, path
        # Public login is generated by a router, not a static file.
        login = client.get("/web/customer.html").text
        assert '/web/customer-session.js' in login
        assert '/admin-session.js' not in login
        assert 'data-testid="tab-profile">Nastavení</button>' in login
        for path in ("/web/customer-session.js", "/web/legacy-app.js"):
            assert client.get(path, follow_redirects=False).status_code == 200
    assert "form" not in parsed.tags
    assert "input" not in parsed.tags
    assert any(href.startswith("mailto:info@toozservis.cz?subject=") for href in parsed.hrefs)


def test_deletion_is_discoverable_from_privacy_and_web_without_mutating_requests():
    client = public_client()
    for path in ("/web/ochrana-osobnich-udaju.html", "/web/customer.html"):
        response = client.get(path)
        assert response.status_code == 200
        assert "smazani-uctu.html" in Links(response.text).hrefs
    script = (ROOT / "web/legacy-app.js").read_text()
    for label in ("Data a účet", "Trvalé smazání účtu", "SMAZAT UCET", "Smazat účet a data"):
        assert label in script
    assert "apiCall('/user/me', 'DELETE'" in script
    privacy = client.get("/web/ochrana-osobnich-udaju.html").text
    assert "90 dnů" in privacy
    assert "Google (Google Play)" in privacy
    assert "pouze chráněné otisky adresy a kódu" not in privacy
